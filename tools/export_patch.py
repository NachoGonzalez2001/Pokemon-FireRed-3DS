#!/usr/bin/env python3
"""Turn the build tree's uncommitted upstream changes into the next port patch.

    python tools/export_patch.py 0002-assembler-and-data-syntax [--tree C:/fr3ds/upstream]
    python tools/export_patch.py 0004-platform-layer --rev HEAD     # re-export a commit

bootstrap.py leaves one commit per existing patch in the tree. Edits made on
top of that (the overlay of 3ds_port/ and our tools is excluded) are staged,
written to patches/pokefirered/<name>.patch with LF line endings and a header
naming the pinned upstream commit, and committed in the tree, so the next
patch starts from there. With --rev, an existing commit is exported instead.
"""

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(tree, *args, capture=True):
    return subprocess.run(["git", "-c", "core.autocrlf=false", *args], cwd=tree,
                          capture_output=capture, check=True).stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--tree", default="C:/fr3ds/upstream")
    ap.add_argument("--rev")
    a = ap.parse_args()
    lock = tomllib.loads((ROOT / "upstream.lock").read_text(encoding="utf-8"))
    commit = lock["pokefirered"]["commit"]
    if a.rev:
        diff = git(a.tree, "diff", "--full-index", "--binary", a.rev + "~1", a.rev)
    else:
        git(a.tree, "add", "-A")
        diff = git(a.tree, "diff", "--cached", "--full-index", "--binary", "HEAD")
    if not diff.strip():
        sys.exit("nothing to export")
    title = a.name.split("-", 1)[1].replace("-", " ")
    header = ("Pokémon FireRed 3DS changes to pret/pokefirered %s: %s\n"
              "Generated by tools/export_patch.py; apply with tools/bootstrap.py.\n\n"
              % (commit, title)).encode("utf-8")
    out = ROOT / "patches" / "pokefirered" / (a.name + ".patch")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(header + diff.replace(b"\r\n", b"\n"))
    if not a.rev:
        git(a.tree, "-c", "user.name=bootstrap", "-c", "user.email=bootstrap@localhost",
            "commit", "-q", "--no-verify", "-m", a.name)
        # the tree now holds exactly the exported patch set
        import hashlib
        digest = hashlib.sha256()
        for p in sorted(out.parent.glob("*.patch")):
            digest.update(p.name.encode())
            digest.update(p.read_bytes())
        (Path(a.tree) / ".firered3ds-patches").write_text(digest.hexdigest() + "\n")
    print("wrote %s (%d bytes)" % (out, out.stat().st_size))


if __name__ == "__main__":
    main()
