#!/usr/bin/env python3
"""Export one commit of the build tree's work branch as a port patch.

    python tools/export_patch.py 0004-platform-layer [--tree C:/fr3ds/upstream] [--rev HEAD]

Writes patches/pokefirered/<name>.patch from `git diff <rev>~1 <rev>` in the
tree, LF line endings, with a header naming the pinned upstream commit. The
work branch (port-work) holds one commit per patch, in patch order, on top of
the pinned commit; bootstrap.py applies the exported files in the same order.
"""

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--tree", default="C:/fr3ds/upstream")
    ap.add_argument("--rev", default="HEAD")
    a = ap.parse_args()
    lock = tomllib.loads((ROOT / "upstream.lock").read_text(encoding="utf-8"))
    commit = lock["pokefirered"]["commit"]
    diff = subprocess.run(["git", "-c", "core.autocrlf=false", "diff", "--full-index", "--binary",
                           a.rev + "~1", a.rev], cwd=a.tree, capture_output=True, check=True).stdout
    if not diff.strip():
        sys.exit("empty diff")
    title = a.name.split("-", 1)[1].replace("-", " ")
    header = ("Pokémon FireRed 3DS changes to pret/pokefirered %s: %s\n"
              "Generated by tools/export_patch.py; apply with tools/bootstrap.py.\n\n"
              % (commit, title)).encode("utf-8")
    out = ROOT / "patches" / "pokefirered" / (a.name + ".patch")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(header + diff.replace(b"\r\n", b"\n"))
    print("wrote %s (%d bytes)" % (out, out.stat().st_size))


if __name__ == "__main__":
    main()
