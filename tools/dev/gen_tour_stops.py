#!/usr/bin/env python3
"""Stops for the debug tour (CTR_DEBUG_TOUR in 3ds_game_full.c): every map,
outdoors a stop every TILE_W x TILE_H cells, indoors one by its first warp
(or its middle), each on a walkable cell. Writes a C header.

    POKEFIRERED=C:/fr3ds/upstream python gen_tour_stops.py OUT.h [--only SUBSTR,...] [--start N]
"""
import argparse
import json
import os
import sys

ROOT = os.environ.get("POKEFIRERED", "C:/fr3ds/upstream")
sys.path.insert(0, os.path.join(ROOT, "3ds_port", "scripts"))
import fr_map_render  # noqa: E402

TILE_W, TILE_H = 28, 20
OUTDOOR = {"MAP_TYPE_TOWN", "MAP_TYPE_CITY", "MAP_TYPE_ROUTE", "MAP_TYPE_OCEAN_ROUTE"}


def walkable(layout, x, y):
    return 0 <= x < layout.w and 0 <= y < layout.h and not layout.collision(x, y)


def nearest(layout, cx, cy, box=None):
    best = None
    x0, y0, x1, y1 = box or (0, 0, layout.w, layout.h)
    for y in range(y0, y1):
        for x in range(x0, x1):
            if walkable(layout, x, y):
                d = (x - cx) ** 2 + (y - cy) ** 2
                if best is None or d < best[0]:
                    best = (d, x, y)
    return best and best[1:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--only", help="comma-separated substrings of map names")
    args = ap.parse_args()
    only = args.only.split(",") if args.only else None
    groups = json.load(open(os.path.join(ROOT, "data", "maps", "map_groups.json")))
    stops = []
    for g, group in enumerate(groups["group_order"]):
        if group == "gMapGroup_Link":
            continue
        for n, name in enumerate(groups[group]):
            if only and not any(s in name for s in only):
                continue
            m = json.load(open(os.path.join(ROOT, "data", "maps", name, "map.json")))
            try:
                layout = fr_map_render.FrLayout(m["layout"])
            except Exception:
                continue
            points = []
            if m.get("map_type") in OUTDOOR:
                for ty in range(0, layout.h, TILE_H):
                    for tx in range(0, layout.w, TILE_W):
                        box = (tx, ty, min(layout.w, tx + TILE_W), min(layout.h, ty + TILE_H))
                        p = nearest(layout, tx + TILE_W // 2, ty + TILE_H // 2 + 2, box)
                        if p:
                            points.append(p)
            else:
                for w in m.get("warp_events", [])[:1]:
                    if walkable(layout, w["x"], w["y"] - 1):
                        points.append((w["x"], w["y"] - 1))
                if not points:
                    p = nearest(layout, layout.w // 2, layout.h // 2 + 2)
                    if p:
                        points.append(p)
            for i, (x, y) in enumerate(points):
                stops.append((g, n, x, y, "%s_%d" % (name, i)))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/dev/gen_tour_stops.py: the debug tour's stops. */\n")
        f.write("static const struct { u8 group, num; s16 x, y; const char *name; } sTourStops[] = {\n")
        for s in stops:
            f.write('    { %d, %d, %d, %d, "%s" },\n' % s)
        f.write("};\n")
    print("%d stops -> %s" % (len(stops), args.out))


if __name__ == "__main__":
    main()
