"""The Mega Evolution effect's sprites (3DS port), drawn here.

usage: python mega_fx.py OUT_C [PREVIEW_PNG]

Nothing is taken from any game: rainbow orbs that gather round the Pokémon,
a ring of light that closes over it and the shards it bursts into. One
16-colour palette for all; 4bpp tiles in the GBA's 1D sprite order.
Writes OUT_C with gMegaFxPal, gMegaFxOrbs (MEGA_FX_HUES 8x8 tiles, one per
hue), gMegaFxRing (a 64x64 sprite) and gMegaFxShard (one 8x8 tile).
"""
import math
import sys

from PIL import Image

WHITE = (255, 255, 255)
PALE = (255, 248, 214)
HUES = [(255, 84, 96), (255, 168, 64), (255, 236, 92), (96, 228, 128), (80, 176, 255), (184, 112, 255)]


def mix(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


LIGHT = [mix(h, WHITE, .55) for h in HUES]
PAL = [(0, 0, 0), WHITE, PALE] + LIGHT + HUES + [(72, 48, 132)]
assert len(PAL) == 16
I_WHITE, I_PALE, I_LIGHT, I_MID, I_DEEP = 1, 2, 3, 3 + len(HUES), 15


def orb(h):
    """An 8x8 orb of light: white heart, light then full hue round it."""
    px = [0] * 64
    for y in range(8):
        for x in range(8):
            d = math.hypot(x - 3.5, y - 3.5)
            if d < 1.6:
                px[y * 8 + x] = I_WHITE
            elif d < 2.6:
                px[y * 8 + x] = I_LIGHT + h
            elif d < 3.7:
                px[y * 8 + x] = I_MID + h
    return px


def ring():
    """A 64x64 sphere of light: white at the heart, its rim a ring whose hue
    goes round it."""
    px = [0] * (64 * 64)
    for y in range(64):
        for x in range(64):
            dx, dy = x - 31.5, y - 31.5
            d = math.hypot(dx, dy)
            h = int(((math.atan2(dy, dx) / (2 * math.pi)) % 1) * len(HUES)) % len(HUES)
            if 22.5 <= d < 24:
                px[y * 64 + x] = I_WHITE
            elif 24 <= d < 26.5:
                px[y * 64 + x] = I_LIGHT + h
            elif 26.5 <= d < 29.5:
                px[y * 64 + x] = I_MID + h
            elif d < 13:
                px[y * 64 + x] = I_WHITE
            elif d < 18:
                px[y * 64 + x] = I_WHITE if (x + y) % 2 else I_PALE
            elif d < 22.5:
                px[y * 64 + x] = I_PALE
    return px


def shard():
    """A small diamond of light."""
    rows = ["...11...", "..1221..", ".12aa21.", "12aaaa21", ".12aa21.", "..1221..", "...11...", "........"]
    m = {".": 0, "1": I_PALE, "2": I_WHITE, "a": I_WHITE}
    return [m[c] for r in rows for c in r]


def tiles(px, w, h):
    data = bytearray()
    for ty in range(h // 8):
        for tx in range(w // 8):
            for y in range(8):
                for x in range(0, 8, 2):
                    p = (ty * 8 + y) * w + tx * 8 + x
                    data.append(px[p] | px[p + 1] << 4)
    return bytes(data)


def words(b):
    w = ["0x%08X" % int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4)]
    return "\n".join("    " + ",".join(w[i:i + 8]) + "," for i in range(0, len(w), 8))


def bgr555(c):
    r, g, b = (v >> 3 for v in c)
    return r | g << 5 | b << 10


def picture(px, w, h):
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for i, p in enumerate(px):
        if p:
            im.putpixel((i % w, i // w), PAL[p] + (255,))
    return im


def main(out_c, preview=None):
    orbs = b"".join(tiles(orb(h), 8, 8) for h in range(len(HUES)))
    lines = ["/* Generated by tools/dev/mega_fx.py: the Mega Evolution effect's sprites,",
             " * drawn there (not from any game). */",
             '#include "global.h"', "",
             "const u16 gMegaFxPal[16] = { %s };" % ",".join("0x%04X" % bgr555(c) for c in PAL), "",
             "const u32 gMegaFxOrbs[%d] = {" % (len(orbs) // 4), words(orbs), "};", "",
             "const u32 gMegaFxRing[%d] = {" % (64 * 64 // 8), words(tiles(ring(), 64, 64)), "};", "",
             "const u32 gMegaFxShard[8] = {", words(tiles(shard(), 8, 8)), "};", ""]
    open(out_c, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    if preview:
        sheet = Image.new("RGBA", (64 + 8 + 8 * len(HUES) + 16, 64), (24, 28, 40, 255))
        sheet.alpha_composite(picture(ring(), 64, 64), (0, 0))
        for h in range(len(HUES)):
            sheet.alpha_composite(picture(orb(h), 8, 8), (72 + 8 * h, 8))
        sheet.alpha_composite(picture(shard(), 8, 8), (72, 24))
        sheet.resize((sheet.width * 6, sheet.height * 6), Image.NEAREST).save(preview)
    print("wrote", out_c)


if __name__ == "__main__":
    main(*sys.argv[1:3])
