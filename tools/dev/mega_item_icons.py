"""The port's own bag icons for the Mega Evolution items (3DS port).

usage: python mega_item_icons.py OUT_C [PREVIEW_PNG]

Drawn here, not taken from any game: the MEGA STONE (warm), the MEGA STONE Y
(cool) and the KEY STONE (a stone set in a bracelet), each a 24x24, 15-colour
picture as the GBA's item icons are. Shapes are drawn at 8x with the helpers
of ui_icons.py, box-filtered down, given a hard outline and cut to 15 colours.
Writes OUT_C: per icon, LZ77 tiles and an LZ77 palette, the format
GetItemIconGfxPtr hands out; the order is the one of MEGA_ICON_* in
include/battle_mega.h.
"""
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ui_icons import Ic  # noqa: E402

N = 24
OUTLINE = (40, 32, 56)


def helix(c, stone, cx, cy, r, a, b):
    """The swirl inside a Mega Stone: two strands twisting round each other,
    slanted across the stone."""
    import math
    ang = math.radians(-38)
    pa, pb = [], []
    for i in range(25):
        t = i / 24
        u = (t - .5) * r * 1.7
        v = r * .34 * math.sin((t - .5) * 1.6 * math.pi)
        for pts, sv in ((pa, v), (pb, -v)):
            pts.append((cx + u * math.sin(ang) * -1 + sv * math.cos(ang), cy + u * math.cos(ang) + sv * math.sin(ang)))
    c.line(pb, 1.3, b, clip=stone, alpha=255)
    c.line(pa, 1.3, a, clip=stone, alpha=255)


def mega_stone(light, dark, a, b):
    cx, cy, r = 12, 12.6, 8.0
    c = Ic(N)
    stone = c.circ(cx, cy, r, light, dark)
    c.circ(cx + 2.2, cy + 2.6, r * .62, dark, None, clip=stone, alpha=90)
    helix(c, stone, cx, cy, r, a, b)
    c.ell(cx - 6.2, cy - 6.6, cx - 1.4, cy - 3.4, (255, 255, 255), None, clip=stone, alpha=240)
    return c


def stone_x():
    return mega_stone((255, 178, 96), (178, 36, 52), (255, 246, 196), (90, 206, 255))


def stone_y():
    return mega_stone((128, 214, 255), (44, 60, 188), (255, 246, 196), (255, 120, 196))


def key_stone():
    """The Mega Ring: a silver bracelet seen from above, its Key Stone set
    in front."""
    c = Ic(N)
    c.ell(1.4, 4.6, 22.6, 19.4, (238, 242, 250), (108, 118, 142))
    c.ell(5.2, 6.8, 18.8, 14.6, (52, 56, 78), (30, 32, 46))
    c.ell(5.6, 13.4, 18.4, 15.8, (150, 160, 182), None, alpha=200)
    c.circ(12, 15.6, 6.4, (250, 252, 255), (136, 146, 172))
    stone = c.circ(12, 15.6, 4.8, (255, 132, 206), (104, 66, 214))
    c.ell(7.4, 11.2, 12.6, 16.0, (120, 232, 160), None, clip=stone, alpha=220)
    c.ell(11.6, 15.0, 17.2, 20.4, (90, 176, 255), None, clip=stone, alpha=220)
    c.circ(12, 15.6, 1.5, (255, 240, 130), None, alpha=240)
    c.ell(8.8, 12.4, 11.0, 14.2, (255, 255, 255), None, alpha=240)
    return c


ICONS = [("MEGA STONE", stone_x), ("MEGA STONE Y", stone_y), ("KEY STONE", key_stone)]


def render(fn):
    """24x24 RGBA with a 1 px outline and hard alpha, cut to 15 colours."""
    im = fn().done(OUTLINE)
    a = im.getchannel("A").point(lambda v: 255 if v >= 96 else 0)
    rgb = Image.new("RGB", im.size, (0, 0, 0))
    rgb.paste(im.convert("RGB"), mask=a)
    q = rgb.quantize(15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:45]
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    idx = []
    for y in range(N):
        for x in range(N):
            if a.getpixel((x, y)):
                i = q.getpixel((x, y))
                idx.append(i + 1)
                out.putpixel((x, y), tuple(pal[3 * i:3 * i + 3]) + (255,))
            else:
                idx.append(0)
    colours = [tuple(pal[i:i + 3]) for i in range(0, 45, 3)]
    return out, idx, colours


def tiles(idx):
    data = bytearray()
    for ty in range(3):
        for tx in range(3):
            for y in range(8):
                for x in range(0, 8, 2):
                    p = (ty * 8 + y) * N + tx * 8 + x
                    data.append(idx[p] | idx[p + 1] << 4)
    return bytes(data)


def bgr555(c):
    r, g, b = (v >> 3 for v in c)
    return r | g << 5 | b << 10


def lz77(data):
    """A valid LZ77 (type 0x10) stream of literals only: GBA BIOS format."""
    out = bytearray([0x10, len(data) & 0xFF, len(data) >> 8 & 0xFF, len(data) >> 16 & 0xFF])
    for i in range(0, len(data), 8):
        out.append(0)
        out += data[i:i + 8]
    while len(out) % 4:
        out.append(0)
    return bytes(out)


def words(b):
    return ",".join("0x%08X" % int.from_bytes(b[i:i + 4], "little") for i in range(0, len(b), 4))


def main(out_c, preview=None):
    lines = ["/* Generated by tools/dev/mega_item_icons.py: the port's own bag icons for the",
             " * Mega Evolution items, drawn there (not from any game). LZ77, as the game's",
             " * item icons. */",
             '#include "global.h"', ""]
    sheet = Image.new("RGBA", (N * len(ICONS), N), (0, 0, 0, 0))
    names = []
    for k, (name, fn) in enumerate(ICONS):
        im, idx, colours = render(fn)
        sheet.alpha_composite(im, (N * k, 0))
        pal = [0] + [bgr555(c) for c in colours]
        palbytes = b"".join(v.to_bytes(2, "little") for v in pal)
        lines.append("static const u32 sTiles%d[] = { %s };" % (k, words(lz77(tiles(idx)))))
        lines.append("static const u32 sPal%d[] = { %s }; /* %s */" % (k, words(lz77(palbytes)), name))
        names.append(k)
    lines.append("")
    lines.append("const u32 *const gMegaItemIcons[%d][2] = {" % len(ICONS))
    for k in names:
        lines.append("    { sTiles%d, sPal%d }," % (k, k))
    lines += ["};", ""]
    open(out_c, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    if preview:
        sheet.resize((sheet.width * 8, N * 8), Image.NEAREST).save(preview)
    print("wrote", out_c)


if __name__ == "__main__":
    main(*sys.argv[1:3])
